const dict: Record<Language, Record<TranslationKey, string>> = { en, hi, bn };
export function t(lang: Language, key: TranslationKey, params?: Record<string, string | number>): string {
  const raw: string = dict[lang][key];
  return raw.replace(/\{(\w+)\}/g, (_match, part: string) => String(params?.[part] ?? `{${part}}`));
}
export const documentLabel = (lang: Language, type: DocumentType): string => t(lang, type);
export function fieldLabel(lang: Language, key: string): string {
  if (key === 'name') return t(lang, 'fieldName');
  if (key === 'dob' || key === 'date_of_birth') return t(lang, 'fieldDob');
  if (key === 'address') return t(lang, 'fieldAddress');
  return key;
}
export const applicantLabel = (lang: Language, type: string): string => {
  switch (type) {
    case 'owner': return t(lang, 'applicantOwner');
    case 'tenant': return t(lang, 'applicantTenant');
    case 'joint': return t(lang, 'applicantJoint');
    case 'other': return t(lang, 'applicantOther');
    default: return type;
  }
};
export function money(value: number | null, lang: Language): string {
  if (value == null) return t(lang, 'amountMissing');
  const locale = lang === 'bn' ? 'bn-IN' : lang === 'hi' ? 'hi-IN' : 'en-IN';
  return new Intl.NumberFormat(locale, { style: 'currency', currency: 'INR', maximumFractionDigits: 0 }).format(value);
}
